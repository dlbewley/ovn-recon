import * as React from 'react';
import { Link } from 'react-router';
import { Flex, FlexItem, Label, LabelGroup, PageSection, Spinner, Title } from '@patternfly/react-core';

import { ConsoleLink, LinkOutProvider, SecondaryLinks } from '../linkOut/LinkOut';
import { resourceTarget } from '../linkOut/registry';
import { networkPath } from '../routes';
import { ProvenanceLabel } from '../topology/facts';
import {
    NETWORK_KIND_TITLE,
    networkDisplayName,
    networkHeaderFacts,
    networkNotCreated,
    networkRowFor,
    networkScopeState,
    NetworkView,
} from './networkScopeModel';
import { NETWORK_KIND_LABEL } from './overviewModel';
import type { ExplorerData } from './useExplorerData';

/**
 * The network scope of the explorer (ovn-recon-gbr.6): a header naming the network,
 * its kind and its key facts, with its console links, over the network page's own
 * body (`NetworkExplorerBody`: findings, summary and placement by node). It has no
 * tabs: a network has one view. The body is loaded when a network is first opened,
 * so the shell's own chunk does not carry it.
 */

const NetworkExplorerBody = React.lazy(() => import('./NetworkDetails')
    .then((module) => ({ default: module.NetworkExplorerBody })));

const subtle: React.CSSProperties = { color: 'var(--pf-t--global--text--color--subtle)' };

/**
 * The header, drawn from the shell's watches so it agrees with the tree. The name and
 * kind come from the URL and show at once; the facts and links follow once the
 * network is found. A missing network keeps its name here, and the body says it is
 * not found.
 */
export const NetworkScopeHeader: React.FC<{ view: NetworkView; data: ExplorerData }> = ({ view, data }) => {
    const address = view.params.network;
    const state = networkScopeState(address, data.networkInputs, data.networksLoaded);
    const record = state.status === 'found' ? state.record : undefined;
    const row = record ? networkRowFor(data.networkRows, address) : undefined;
    return (
        <PageSection
            padding={{ default: 'noPadding' }}
            style={{ paddingInline: 'var(--pf-t--global--spacer--lg)', paddingBlockStart: 'var(--pf-t--global--spacer--md)' }}
            data-testid="network-scope-header"
        >
            <Flex alignItems={{ default: 'alignItemsCenter' }} spaceItems={{ default: 'spaceItemsMd' }} rowGap={{ default: 'rowGapSm' }}>
                <FlexItem>
                    <Title headingLevel="h2" size="xl" data-testid="network-scope-name">{networkDisplayName(address)}</Title>
                </FlexItem>
                <FlexItem>
                    <LabelGroup>
                        <Label isCompact color="blue" title={NETWORK_KIND_TITLE[address.kind]}>
                            {NETWORK_KIND_LABEL[address.kind]}
                        </Label>
                        {record && networkNotCreated(record) && (
                            <Label isCompact status="danger" data-testid="network-scope-not-created">Not created</Label>
                        )}
                    </LabelGroup>
                </FlexItem>
                {record && (
                    <FlexItem>
                        <span style={subtle} data-testid="network-scope-facts">{networkHeaderFacts(record, row).join(' · ')}</span>
                    </FlexItem>
                )}
                {record && (
                    <FlexItem>
                        <LinkOutProvider>
                            <Flex spaceItems={{ default: 'spaceItemsMd' }}>
                                <FlexItem>
                                    <ConsoleLink target={resourceTarget(record.resourceRef)} hideWhenAbsent data-testid="network-console-link">
                                        View {NETWORK_KIND_LABEL[record.kind]} in the console
                                    </ConsoleLink>
                                </FlexItem>
                                <FlexItem>
                                    <SecondaryLinks target={resourceTarget(record.resourceRef)} />
                                </FlexItem>
                            </Flex>
                        </LinkOutProvider>
                    </FlexItem>
                )}
            </Flex>
            {record?.owner && (
                <p className="pf-v6-u-mt-xs" style={subtle} data-testid="network-owner">
                    Generated by {NETWORK_KIND_TITLE[record.owner.kind]}{' '}
                    <Link to={networkPath(record.owner)}>{networkDisplayName(record.owner)}</Link>
                    {record.owner.inferred && <ProvenanceLabel provenance="inferred" hint={record.owner.inferred} />}
                </p>
            )}
        </PageSection>
    );
};

const Loading: React.FC = () => (
    <PageSection><Spinner size="lg" aria-label="Loading" /></PageSection>
);

/** The network page's body under the header. */
export const NetworkScopeBody: React.FC<{ view: NetworkView }> = ({ view }) => (
    <React.Suspense fallback={<Loading />}>
        <NetworkExplorerBody address={view.params.network} />
    </React.Suspense>
);
