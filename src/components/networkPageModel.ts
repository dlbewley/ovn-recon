export interface StatusCondition {
    type: string;
    status: string;
    reason?: string;
    message?: string;
}

export const networkConditions = (record: NetworkRecord): StatusCondition[] =>
    record.kind === 'nad'
        ? []
        : ((record.resource as ClusterUserDefinedNetwork | UserDefinedNetwork).status?.conditions ?? []) as StatusCondition[];

/**
 * The NetworkCreated condition when it is False: OVN-Kubernetes did not create the
 * network, so nothing else on its page describes something that exists. Undefined when
 * the condition is True, Unknown or absent; absence is not a failure.
 */
export const networkCreationFailure = (record: NetworkRecord): StatusCondition | undefined =>
    networkConditions(record).find((condition) => condition.type === 'NetworkCreated' && condition.status === 'False');

/** The NADs a CUDN or UDN generated, by owner reference, else by the naming convention. */
export const generatedNads = (record: NetworkRecord, inputs: NetworkInputs): NetworkAttachmentDefinition[] => {
    if (record.kind === 'nad') return [];
    return inputs.nads
        .filter((nad) => {
            const owner = findNadOwner(nad, inputs);
            return owner?.kind === record.kind && owner.name === record.name
                && (record.kind === 'cudn' || owner.namespace === record.namespace);
        })
        .sort((a, b) => namespaceOf(a).localeCompare(namespaceOf(b)) || (a.metadata?.name || '').localeCompare(b.metadata?.name || ''));
};

/** The spec block that carries a network's layer settings: subnets, MTU, IPAM. */
const layerSpec = (record: NetworkRecord): Record<string, unknown> | undefined => {
    if (record.kind === 'cudn') {
        const network = asRecord((record.resource as ClusterUserDefinedNetwork).spec?.network);
        const key = record.topology === 'Layer2' ? 'layer2'
            : record.topology === 'Layer3' ? 'layer3'
                : (network?.localnet ? 'localnet' : 'localNet');
        return asRecord(network?.[key]);
    }
    if (record.kind === 'udn') {
        const spec = asRecord((record.resource as UserDefinedNetwork).spec);
        return asRecord(spec?.[record.topology === 'Layer3' ? 'layer3' : 'layer2']);
    }
    return parseNadConfig((record.resource as NetworkAttachmentDefinition).spec?.config) ?? undefined;
};

const layerPath = (record: NetworkRecord): string => {
    if (record.kind === 'nad') return 'spec.config';
    const key = record.topology === 'Layer3' ? 'layer3' : record.topology === 'Localnet' ? 'localnet' : 'layer2';
    return record.kind === 'cudn' ? `spec.network.${key}` : `spec.${key}`;
};

const subnetsFact = (record: NetworkRecord, spec: Record<string, unknown> | undefined): Fact[] => {
    if (record.kind === 'nad') {
        const subnets = asString(spec?.subnets);
        return subnets ? [{ label: 'Subnets', value: subnets, provenance: 'declared', hint: 'spec.config.subnets' }] : [];
    }
    const subnets = spec?.subnets as (string | Layer3Subnet)[] | undefined;
    // Layer2 and Layer3 always show the row; a Localnet network only when it has subnets.
    if (record.topology !== 'Layer2' && record.topology !== 'Layer3' && !(Array.isArray(subnets) && subnets.length > 0)) {
        return [];
    }
    return [{ label: 'Subnets', value: formatSubnets(subnets) || '-', provenance: 'declared', hint: `${layerPath(record)}.subnets` }];
};

const vlanFact = (record: NetworkRecord, spec: Record<string, unknown> | undefined): Fact[] => {
    const vlan = record.kind === 'nad'
        ? asPositive(spec?.vlanID) ?? asPositive(spec?.vlan)
        : asPositive(asRecord(asRecord(spec?.vlan)?.access)?.id);
    if (!vlan) return [];
    const path = record.kind === 'nad'
        ? (asPositive(spec?.vlanID) ? 'spec.config.vlanID' : 'spec.config.vlan')
        : `${layerPath(record)}.vlan.access.id`;
    return [{ label: 'VLAN', value: String(vlan), provenance: 'declared', hint: path }];
};

const mtuFact = (record: NetworkRecord, spec: Record<string, unknown> | undefined, inputs: NetworkInputs): Fact[] => {
    const declared = asPositive(spec?.mtu);
    if (declared) {
        return [{ label: 'MTU', value: String(declared), provenance: 'declared', hint: `${layerPath(record)}.mtu` }];
    }
    // A CUDN or UDN that declares none: the MTU its generated NAD carries is what
    // OVN-Kubernetes applied (the same reading as getLocalnetNetworks).
    const fromNad = generatedNads(record, inputs)
        .map((nad) => ({ nad, mtu: asPositive(parseNadConfig(nad.spec?.config)?.mtu) }))
        .find((entry) => entry.mtu);
    if (!fromNad) return [];
    return [{
        label: 'MTU',
        value: String(fromNad.mtu),
        provenance: 'declared',
        hint: `The network declares no MTU; read from NAD ${namespaceOf(fromNad.nad)}/${fromNad.nad.metadata?.name} spec.config.mtu.`
    }];
};

const ipamFact = (record: NetworkRecord, spec: Record<string, unknown> | undefined): Fact[] => {
    if (record.kind === 'nad') {
        const ipam = asRecord(spec?.ipam);
        const type = asString(ipam?.type);
        if (type) return [{ label: 'IPAM', value: type, provenance: 'declared', hint: 'spec.config.ipam.type' }];
        return [];
    }
    const ipam = asRecord(spec?.ipam);
    const parts = [
        asString(ipam?.mode) ? `mode ${ipam?.mode}` : undefined,
        asString(ipam?.lifecycle) ? `lifecycle ${ipam?.lifecycle}` : undefined
    ].filter((part): part is string => Boolean(part));
    return parts.length > 0
        ? [{ label: 'IPAM', value: parts.join(', '), provenance: 'declared', hint: `${layerPath(record)}.ipam` }]
        : [];
};

const physicalNetworkFact = (record: NetworkRecord): Fact[] => {
    if (record.physicalNetworkName) {
        return [{
            label: 'Physical network',
            value: record.physicalNetworkName,
            provenance: record.physicalNetworkInferred ? 'inferred' : 'declared',
            hint: record.physicalNetworkInferred ?? `${layerPath(record)}.physicalNetworkName`
        }];
    }
    if (record.bridge) {
        return [{
            label: 'Bridge',
            value: record.bridge,
            provenance: record.bridgeInferred ? 'inferred' : 'declared',
            hint: record.bridgeInferred ?? 'spec.config.bridge'
        }];
    }
    return [];
};

const nadItem = (nad: NetworkAttachmentDefinition): FactItem => ({
    text: `${namespaceOf(nad)}/${nad.metadata?.name}`,
    ref: { apiVersion: NAD_API, kind: 'NetworkAttachmentDefinition', name: nad.metadata?.name || '', namespace: namespaceOf(nad) }
});

const namespaceFacts = (record: NetworkRecord): Fact[] => {
    if (record.kind !== 'cudn') {
        return [{
            label: 'Namespace',
            value: [{ text: record.namespace || 'default', href: getProjectPath(record.namespace || 'default') }],
            provenance: 'declared'
        }];
    }
    const cudn = record.resource as ClusterUserDefinedNetwork;
    const selector = cudn.spec?.namespaceSelector;
    const selectorText = selector ? (formatLabelSelector(selector) || 'Matches all namespaces (empty selector)') : '';
    const queryPath = getNamespaceQueryPath(selector);
    return [
        ...(selector
            ? [{
                label: 'Namespace selector',
                value: queryPath ? [{ text: selectorText, href: queryPath }] : selectorText,
                provenance: 'declared',
                hint: 'spec.namespaceSelector: the declared rule that scopes namespaces into this network.'
            } as Fact]
            : []),
        {
            label: 'Namespaces',
            value: getCudnAssociatedNamespaces(cudn).map((ns): FactItem => ({ text: ns, href: getProjectPath(ns) })),
            provenance: 'inferred',
            hint: 'The namespaces the namespaceSelector scoped in, parsed out of the '
                + 'NetworkCreated condition message; the API does not list them directly.',
            emptyText: 'None named by the NetworkCreated condition.'
        }
    ];
};

const raRef = (name: string): ResourceRef => ({ apiVersion: OVN_API, kind: 'RouteAdvertisements', name });

const routeAdvertisementFacts = (record: NetworkRecord, inputs: NetworkInputs): Fact[] => {
    // RouteAdvertisements select CUDNs by label, and only Layer2 or Layer3 ones
    // (routeAdvertisementSelectsCudn); the other kinds have nothing to show here.
    if (record.kind !== 'cudn' || (record.topology !== 'Layer2' && record.topology !== 'Layer3')) return [];
    const matching = getRouteAdvertisementsMatchingCudn(inputs.routeAdvertisements, record.resource as ClusterUserDefinedNetwork);
    return [{
        label: 'Route advertisements',
        value: matching.map((ra): FactItem => ({ text: ra.metadata?.name || 'Unknown', ref: raRef(ra.metadata?.name || '') })),
        provenance: 'declared',
        hint: 'RouteAdvertisements whose networkSelector matches this CUDN\'s labels.',
        emptyText: 'None select this network.'
    }];
};

/** The page's summary: what the network is, who uses it, what selects it. */
export const networkSummaryFacts = (record: NetworkRecord, inputs: NetworkInputs): Fact[] => {
    const spec = layerSpec(record);
    const nads = generatedNads(record, inputs);
    return [
        record.clusterDefault
            ? {
                label: 'Network',
                value: CLUSTER_DEFAULT_LABEL,
                provenance: 'declared',
                hint: 'OVN-Kubernetes creates this NetworkAttachmentDefinition for the cluster\'s default pod network. '
                    + 'Its config declares no topology.'
            }
            : { label: 'Topology', value: record.topology, provenance: 'declared' },
        ...(record.role ? [{ label: 'Role', value: record.role, provenance: 'declared' } as Fact] : []),
        ...(record.cniType ? [{ label: 'CNI type', value: record.cniType, provenance: 'declared', hint: 'spec.config.type' } as Fact] : []),
        ...subnetsFact(record, spec),
        ...vlanFact(record, spec),
        ...physicalNetworkFact(record),
        ...mtuFact(record, spec, inputs),
        ...ipamFact(record, spec),
        ...namespaceFacts(record),
        ...(record.kind !== 'nad'
            ? [{
                label: 'NetworkAttachmentDefinitions',
                value: nads.map(nadItem),
                provenance: 'observed',
                hint: 'NADs this network generated: those whose owner reference names it or, lacking one, '
                    + 'whose config carries its network name.',
                emptyText: 'None found.'
            } as Fact]
            : []),
        ...routeAdvertisementFacts(record, inputs)
    ];
};

