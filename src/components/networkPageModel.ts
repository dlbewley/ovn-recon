export interface PlacementVrf {
    name: string;
    state?: string;
    provenance: Provenance;
    hint: string;
    managementPorts: { name: string; state?: string }[];
}

export interface PlacementRow {
    node: string;
    status: PlacementStatus;
    /** The plain fact behind the status. */
    reason: string;
    /** Localnet: the bridge the mapping names, and whether the node reports it. */
    bridge?: { name: string; present: boolean };
    uplinks: PlacementUplink[];
    vrf?: PlacementVrf;
    /** The node's physical view, with the relevant graph node selected. */
    physicalPath: string;
    logicalPath: string;
}

export interface Placement {
    mode: PlacementMode;
    rows: PlacementRow[];
    /** Rows that are wired; meaningless (0) for mode 'none'. */
    wired: number;
    total: number;
}

const BRIDGE_TYPES = ['ovs-bridge', 'linux-bridge'];

const describeUplinks = (bridge: string, interfaces: Interface[]): PlacementUplink[] => {
    const neighbors = extractLldpNeighbors(interfaces);
    return getBridgeUplinks(bridge, interfaces).map((iface) => {
        const carriers = new Set([iface.name, ...getBondMembers(iface)]);
        const lldp = neighbors
            .filter((neighbor) => carriers.has(neighbor.localInterface))
            .map((neighbor) => [neighbor.systemName || neighbor.chassisId, neighbor.portId].filter(Boolean).join(' '))
            .filter(Boolean);
        return {
            name: iface.name,
            type: iface.type,
            state: iface.state,
            mtu: typeof iface.mtu === 'number' ? iface.mtu : undefined,
            ...(lldp.length > 0 ? { lldp } : {})
        };
    });
};

const localnetRow = (record: NetworkRecord, nns: NodeNetworkState, node: string): Omit<PlacementRow, 'logicalPath'> => {
    const physnet = record.physicalNetworkName || '';
    const interfaces = nns.status?.currentState?.interfaces ?? [];
    const mapping = getActiveBridgeMappings(nns).find((m) => m.localnet === physnet);
    if (!mapping) {
        return {
            node,
            status: 'not-wired',
            reason: `No bridge mapping names ${physnet}.`,
            uplinks: [],
            physicalPath: physicalViewPath(node, record.graphNodeId)
        };
    }
    const present = interfaces.some((iface) => iface.name === mapping.bridge && BRIDGE_TYPES.includes(iface.type));
    return {
        node,
        status: present ? 'wired' : 'not-wired',
        reason: present
            ? `${physnet} is mapped to ${mapping.bridge}.`
            : `${physnet} is mapped to ${mapping.bridge}, which this node does not report.`,
        bridge: { name: mapping.bridge, present },
        uplinks: present ? describeUplinks(mapping.bridge, interfaces) : [],
        physicalPath: physicalViewPath(node, bridgeMappingNodeId(physnet))
    };
};

const sameNetwork = (match: PrimaryNetworkMatch, record: NetworkRecord): boolean =>
    match.kind === record.kind && match.name === record.name
    && (record.kind === 'cudn' || match.namespace === record.namespace);

/** The basis of a VRF match in words; mirrors the VRF drawer's Serves Primary Network fact. */
const vrfMatchHint = (match: PrimaryNetworkMatch): string => {
    const corroborated = match.corroboration
        ? ` Port ${match.corroboration.port} address ${match.corroboration.address} lies inside subnet ${match.corroboration.subnet}.`
        : '';
    if (match.signals.includes('status')) return `The network's status.vrfName names this VRF.${corroborated}`;
    if (match.signals.includes('network-id')) {
        return `Matched by network ID: the VRF is named mp${match.networkId}-udn-vrf and NetworkAttachmentDefinition `
            + `${match.nad?.namespace}/${match.nad?.name} carries ${NETWORK_ID_ANNOTATION}: ${match.networkId}.${corroborated}`;
    }
    // The subnet signal only corroborates; its sentence follows.
    return `Matched by ${match.signals.filter((signal) => signal !== 'subnet').join(' and ')}: the VRF carries the network's name, `
        + `or its first 15 characters.${corroborated}`;
};

const primaryRow = (
    record: NetworkRecord,
    nns: NodeNetworkState,
    node: string,
    inputs: NetworkInputs
): Omit<PlacementRow, 'logicalPath'> => {
    const interfaces = nns.status?.currentState?.interfaces ?? [];
    // A primary NAD is matched through the network it belongs to.
    const target: NetworkRecord = record.kind === 'nad' && record.owner
        ? { ...record, kind: record.owner.kind, name: record.owner.name, namespace: record.owner.namespace }
        : record;
    for (const vrf of interfaces.filter((iface) => iface.type === 'vrf')) {
        const match = findPrimaryNetworkForVrf(vrf, inputs.cudns, inputs.udns, interfaces, inputs.nads);
        if (match && sameNetwork(match, target)) {
            const managementPorts = getVrfConnectionInfo(vrf, interfaces).brIntPorts
                .filter((port) => port.name.startsWith(MANAGEMENT_PORT_PREFIX))
                .map((port) => ({ name: port.name, state: port.state }));
            return {
                node,
                status: 'wired',
                reason: `VRF ${vrf.name} serves ${record.name}.`,
                uplinks: [],
                vrf: {
                    name: vrf.name,
                    state: vrf.state,
                    provenance: match.signals.includes('status') ? 'declared' : 'inferred',
                    hint: vrfMatchHint(match),
                    managementPorts
                },
                physicalPath: physicalViewPath(node, vrfNodeId(vrf.name))
            };
        }
    }
    return {
        node,
        status: 'not-wired',
        reason: `No VRF on this node was matched to ${record.name}.`,
        uplinks: [],
        physicalPath: physicalViewPath(node, record.graphNodeId)
    };
};

const bridgeRow = (record: NetworkRecord, nns: NodeNetworkState, node: string): Omit<PlacementRow, 'logicalPath'> => {
    const bridge = record.bridge || '';
    const interfaces = nns.status?.currentState?.interfaces ?? [];
    const present = interfaces.some((iface) => iface.name === bridge);
    return {
        node,
        status: present ? 'wired' : 'not-wired',
        reason: present ? `The node reports ${bridge}.` : `The node does not report ${bridge}.`,
        bridge: { name: bridge, present },
        uplinks: present ? describeUplinks(bridge, interfaces) : [],
        physicalPath: physicalViewPath(node, present ? ifaceNodeId(bridge) : record.graphNodeId)
    };
};

/**
 * One row per node with a NodeNetworkState: is the network wired there, and on what.
 * Rows are sorted by node name; `wired` counts the wired rows.
 */
export const buildPlacement = (
    record: NetworkRecord,
    nodeNetworkStates: NodeNetworkState[],
    inputs: NetworkInputs
): Placement => {
    const rows = nodeNetworkStates
        .map((nns): PlacementRow => {
            const node = nns.metadata?.name || '';
            const row = record.placement === 'localnet' ? localnetRow(record, nns, node)
                : record.placement === 'primary' ? primaryRow(record, nns, node, inputs)
                    : record.placement === 'bridge' ? bridgeRow(record, nns, node)
                        : {
                            node,
                            status: 'not-checked' as const,
                            reason: 'Nothing node-local is checked for this network.',
                            uplinks: [],
                            physicalPath: physicalViewPath(node, record.graphNodeId)
                        };
            return { ...row, logicalPath: logicalViewPath(node) };
        })
        .sort((a, b) => a.node.localeCompare(b.node));
    return {
        mode: record.placement,
        rows,
        wired: rows.filter((row) => row.status === 'wired').length,
        total: rows.length
    };
};

/** "Wired on 4 of 10 nodes", or undefined when the matrix checks nothing for the network. */
export const placementSummary = (placement: Placement): string | undefined => {
    if (placement.mode === 'none') return undefined;
    return `Wired on ${placement.wired} of ${placement.total} node${placement.total === 1 ? '' : 's'}`;
};
