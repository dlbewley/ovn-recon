export interface NetworkIdReading {
    /** The distinct IDs the network's NADs carry; more than one is a disagreement. */
    ids: number[];
    /** The NADs that carry one. */
    nads: NetworkAttachmentDefinition[];
}

/**
 * The network ID OVN-Kubernetes gave a network, from the `k8s.ovn.org/network-id`
 * annotation on its NADs: a NAD's own, a CUDN's or UDN's generated ones. Empty for a
 * network whose NADs carry none, which is every NAD outside OVN-Kubernetes.
 */
export const networkIdOf = (record: NetworkRecord, inputs: NetworkInputs): NetworkIdReading => {
    const candidates = record.kind === 'nad'
        ? [record.resource as NetworkAttachmentDefinition]
        : generatedNads(record, inputs);
    const ids = new Set<number>();
    const nads: NetworkAttachmentDefinition[] = [];
    for (const nad of candidates) {
        const raw = nad.metadata?.annotations?.[NETWORK_ID_ANNOTATION];
        const id = raw === undefined || raw.trim() === '' ? NaN : Number(raw);
        if (!Number.isSafeInteger(id) || id < 0) continue;
        ids.add(id);
        nads.push(nad);
    }
    return { ids: [...ids].sort((a, b) => a - b), nads };
};

/**
 * The `k8s.ovn.org/network` identity of an OVN network: `cluster_udn_<name>` for a
 * CUDN, `<namespace>_<name>` for a UDN, and for a NAD its owner's, else its config's
 * `name`. Undefined for a NAD outside OVN-Kubernetes.
 */
export const ovnNetworkNameOfRecord = (record: NetworkRecord): string | undefined => {
    if (record.kind === 'cudn') return ovnNetworkNameOf({ kind: 'cudn', name: record.name });
    if (record.kind === 'udn') return ovnNetworkNameOf({ kind: 'udn', namespace: record.namespace || 'default', name: record.name });
    if (!isOvnNetwork(record) || record.clusterDefault) return undefined;
    if (record.owner) {
        return record.owner.kind === 'cudn'
            ? ovnNetworkNameOf({ kind: 'cudn', name: record.owner.name })
            : ovnNetworkNameOf({ kind: 'udn', namespace: record.owner.namespace || 'default', name: record.owner.name });
    }
    return asString(parseNadConfig((record.resource as NetworkAttachmentDefinition).spec?.config)?.name);
};

/** Whether the network is a primary one, which alone has gateway routers and a masquerade pair. */
const isPrimaryNetwork = (record: NetworkRecord): boolean =>
    record.role === 'Primary' && isOvnNetwork(record) && !record.clusterDefault;

/**
 * The name OVN-Kubernetes gives a primary network's gateway router on a node:
 * `GR_<network, dashes as dots>_<node>`, as in `GR_cluster_udn_example.p.cudn_worker-1`.
 */
export const gatewayRouterName = (ovnNetwork: string, node: string): string =>
    `GR_${mangleNetworkName(ovnNetwork)}_${node}`;

/** A zone's gateway router for a network: the router carrying its network ID and named `GR_`. */
const gatewayRouterIn = (database: LogicalDatabase, ovnNetwork: string, node: string) => {
    const expected = gatewayRouterName(ovnNetwork, node);
    return database.logicalRouters.find((router) => router.name === expected)
        ?? database.logicalRouters.find((router) =>
            router.name.startsWith('GR_') && router.externalIds?.['k8s.ovn.org/network'] === ovnNetwork);
};

const addressOnly = (text: string): string => text.split('/')[0].trim();

/** Where a zone shows an address on the network's gateway router, in words; undefined when it does not. */
const gatewayRouterEvidence = (
    database: LogicalDatabase,
    ovnNetwork: string,
    node: string,
    address: string,
): string | undefined => {
    const router = gatewayRouterIn(database, ovnNetwork, node);
    if (!router) return undefined;
    const physicalIps = (router.externalIds?.physical_ips ?? router.externalIds?.physical_ip ?? '')
        .split(',').map(addressOnly);
    if (physicalIps.includes(address)) return `${router.name} external_ids:physical_ips on ${node}`;
    const ports = new Set(router.ports);
    const port = database.logicalRouterPorts.find((candidate) =>
        ports.has(candidate.uuid) && (candidate.networks ?? []).some((network) => addressOnly(network) === address));
    if (port) return `${router.name} port ${port.name} on ${node}`;
    const nats = new Set(router.nat ?? []);
    if (database.nats.some((nat) => nats.has(nat.uuid) && nat.externalIp && addressOnly(nat.externalIp) === address)) {
        return `${router.name} SNAT external IP on ${node}`;
    }
    return undefined;
};

/** The address families the network's own subnets declare; empty when it declares none that parse. */
const subnetFamilies = (record: NetworkRecord): Set<4 | 6> => {
    const spec = layerSpec(record);
    const raw = spec?.subnets;
    const texts: string[] = typeof raw === 'string'
        ? raw.split(',')
        : Array.isArray(raw)
            ? raw.map((subnet) => (typeof subnet === 'string' ? subnet : asString(asRecord(subnet)?.cidr) ?? ''))
            : [];
    const families = new Set<4 | 6>();
    for (const text of texts) {
        const prefix = parsePrefix(text.trim());
        if (prefix) families.add(prefix.family);
    }
    return families;
};

const familyLabel = (family: 4 | 6): string => (family === 4 ? 'IPv4' : 'IPv6');

const networkIdFact = (reading: NetworkIdReading): Fact => {
    const sources = reading.nads.map((nad) => `${namespaceOf(nad)}/${nad.metadata?.name}`).join(', ');
    return {
        label: 'Network ID',
        value: reading.ids.join(', '),
        provenance: 'observed',
        hint: reading.ids.length > 1
            ? `The network's NADs disagree: ${sources} carry ${NETWORK_ID_ANNOTATION} values ${reading.ids.join(' and ')}.`
            : `The ${NETWORK_ID_ANNOTATION} annotation OVN-Kubernetes wrote on NAD ${sources}.`
    };
};

const masqueradeFact = (
    record: NetworkRecord,
    networkId: number,
    context: NetworkMasqueradeContext,
): Fact => {
    const zones = context.zones ?? [];
    const allSubnets = masqueradeSubnets({ nodes: context.nodes ?? [], databases: zones.map((zone) => zone.database) });
    // Show the families the network uses; one that declares no subnet shows every family.
    const families = subnetFamilies(record);
    const subnets: MasqueradeSubnet[] = families.size > 0
        ? allSubnets.filter((subnet) => families.has(subnet.family))
        : allSubnets;
    const ovnNetwork = ovnNetworkNameOfRecord(record);
    const items: FactItem[] = [];
    const confirmations: string[] = [];
    const noRoom: string[] = [];
    for (const subnet of subnets) {
        const [pair] = masqueradeIpsForNetworkId(networkId, [subnet]);
        if (!pair) {
            noRoom.push(subnet.cidr);
            continue;
        }
        const evidence = ovnNetwork
            ? zones.map((zone) => gatewayRouterEvidence(zone.database, ovnNetwork, zone.node, pair.gatewayRouter))
                .find((found): found is string => Boolean(found))
            : undefined;
        if (evidence) confirmations.push(`${pair.gatewayRouter} on ${evidence}`);
        const family = familyLabel(pair.family);
        items.push(
            {
                text: pair.gatewayRouter,
                detail: `(${MASQUERADE_ROLE_LABELS['udn-gateway-router']}, ${family}, ${evidence ? 'confirmed' : 'derived'})`
            },
            {
                text: pair.managementPort,
                detail: `(${MASQUERADE_ROLE_LABELS['udn-management-port']}, ${family}, derived)`
            }
        );
    }
    for (const cidr of noRoom) {
        items.push({ text: `No room in ${cidr}`, detail: `(the subnet is too small for network ID ${networkId})` });
    }
    const subnetText = subnets.map((subnet) => `${subnet.cidr} (${subnet.source === 'default'
        ? 'the platform default'
        : subnet.source === 'node-annotation' ? 'from the Nodes\' annotation' : 'from a gateway router\'s static route'})`)
        .join(' and ');
    const derivation = `Derived from network ID ${networkId}: the gateway router takes the subnet's base + 10 + 2 x ID - 1 `
        + `and the management port base + 10 + 2 x ID, in ${subnetText || 'no masquerade subnet'}. `
        + 'The offsets are an OVN-Kubernetes implementation detail, not a documented contract.';
    return {
        label: 'Masquerade IPs',
        value: items,
        provenance: confirmations.length > 0 ? 'observed' : 'inferred',
        hint: confirmations.length > 0
            ? `${derivation} Confirmed by a zone snapshot this tab already holds: ${confirmations.join('; ')}. `
                + 'The management port address sits on the host and is not in OVN\'s databases.'
            : `${derivation} Not yet seen on a gateway router: no zone snapshot this tab holds shows it.`,
        emptyText: 'No masquerade subnet is known.'
    };
};

/**
 * "Network ID" for any network whose NADs carry one, and for a primary network its
 * "Masquerade IPs": the gateway router and management port pair in each masquerade
 * subnet, derived from the ID and confirmed where a remembered zone shows the gateway
 * router address. A secondary network has no gateway router, so no pair.
 */
export const masqueradeFacts = (
    record: NetworkRecord,
    inputs: NetworkInputs,
    context: NetworkMasqueradeContext = {},
): Fact[] => {
    const reading = networkIdOf(record, inputs);
    if (reading.ids.length === 0) return [];
    const facts = [networkIdFact(reading)];
    if (reading.ids.length === 1 && reading.ids[0] >= 1 && isPrimaryNetwork(record)) {
        facts.push(masqueradeFact(record, reading.ids[0], context));
    }
    return facts;
};

/** The page's summary: what the network is, who uses it, what selects it. */
export const networkSummaryFacts = (
    record: NetworkRecord,
    inputs: NetworkInputs,
    masquerade: NetworkMasqueradeContext = {},
): Fact[] => {
    const spec = layerSpec(record);
    const nads = generatedNads(record, inputs);
    return [
        record.clusterDefault
            ? {
                label: 'Network',
                value: CLUSTER_DEFAULT_LABEL,
                provenance: 'declared',
                hint: 'OVN-Kubernetes creates this NetworkAttachmentDefinition for the cluster\'s default pod network. '
                    + 'Its config declares no topology.'
            }
            : { label: 'Topology', value: record.topology, provenance: 'declared' },
        ...(record.role ? [{ label: 'Role', value: record.role, provenance: 'declared' } as Fact] : []),
        ...(record.cniType ? [{ label: 'CNI type', value: record.cniType, provenance: 'declared', hint: 'spec.config.type' } as Fact] : []),
        ...subnetsFact(record, spec),
        ...vlanFact(record, spec),
        ...physicalNetworkFact(record),
        ...mtuFact(record, spec, inputs),
        ...ipamFact(record, spec),
        ...masqueradeFacts(record, inputs, masquerade),
        ...namespaceFacts(record),
        ...(record.kind !== 'nad'
            ? [{
                label: 'NetworkAttachmentDefinitions',
                value: nads.map(nadItem),
                provenance: 'observed',
                hint: 'NADs this network generated: those whose owner reference names it or, lacking one, '
                    + 'whose config carries its network name.',
                emptyText: 'None found.'
            } as Fact]
            : []),
        ...routeAdvertisementFacts(record, inputs)
    ];
};

// --- Placement matrix --------------------------------------------------------

export type PlacementStatus = 'wired' | 'not-wired' | 'not-checked';

export interface PlacementUplink {
    name: string;
    type: string;
    state?: string;
    mtu?: number;
    /** The switch port an LLDP neighbor reports on this uplink or one of its bond members. */
    lldp?: string[];
}

export interface PlacementVrf {
    name: string;
    state?: string;
    provenance: Provenance;
    hint: string;
    managementPorts: { name: string; state?: string }[];
}

export interface PlacementRow {
    node: string;
    status: PlacementStatus;
    /** The plain fact behind the status. */
    reason: string;
    /** Localnet: the bridge the mapping names, and whether the node reports it. */
    bridge?: { name: string; present: boolean };
    uplinks: PlacementUplink[];
    vrf?: PlacementVrf;
    /** The node's physical view, with the relevant graph node selected. */
    physicalPath: string;
    logicalPath: string;
    /**
     * A wired primary network's gateway router on this node, and its construct page on
     * the Routes and NAT tab; set only when the caller says the collector is on.
     */
    gatewayRouter?: { name: string; path: string };
    /** Pods and VMs attached to the network here; set when the caller read them. */
    workloads?: PlacementWorkloads;
}

/** What is attached to a network on one node. */
export interface NodeWorkloadCount {
    pods: number;
    vms: number;
}

/** What is known of the workloads attached to a network. */
export type NetworkWorkloads =
    | { state: 'loading' }
    /** Could not be read, for example without permission to list pods. Never a zero. */
    | { state: 'unknown'; reason: string }
    /** Counting would list every pod in the cluster, so it waits to be asked. */
    | { state: 'on-request' }
    | {
        state: 'known';
        /** Counted by the collector from OVN's switch ports, or from pods read here. */
        source: 'collector' | 'pods';
        /** By node; a node with nothing attached has no entry. */
        counts: ReadonlyMap<string, NodeWorkloadCount>;
        /** The nodes the counts cover, when not all: any other node is unknown. */
        coveredNodes?: ReadonlySet<string>;
        /** Whether the cluster serves VirtualMachineInstances. */
        kubevirt: boolean;
        /** Why VMs could not be counted, when KubeVirt is there but unreadable. */
        vmsUnknown?: string;
        /** When pods were listed, for a count made once on request. */
        countedAt?: string;
    };

/** One node's share of NetworkWorkloads. */
export type PlacementWorkloads =
    | { state: 'loading' }
    | { state: 'unknown' }
    | { state: 'on-request' }
    /** `vms` is absent on a cluster without KubeVirt. */
    | { state: 'known'; pods: number; vms?: number | 'unknown' };

export interface Placement {
    mode: PlacementMode;
    rows: PlacementRow[];
    /** Rows that are wired; meaningless (0) for mode 'none'. */
    wired: number;
    total: number;
}

const BRIDGE_TYPES = ['ovs-bridge', 'linux-bridge'];

const describeUplinks = (bridge: string, interfaces: Interface[]): PlacementUplink[] => {
    const neighbors = extractLldpNeighbors(interfaces);
    return getBridgeUplinks(bridge, interfaces).map((iface) => {
        const carriers = new Set([iface.name, ...getBondMembers(iface)]);
        const lldp = neighbors
            .filter((neighbor) => carriers.has(neighbor.localInterface))
            .map((neighbor) => [neighbor.systemName || neighbor.chassisId, neighbor.portId].filter(Boolean).join(' '))
            .filter(Boolean);
        return {
            name: iface.name,
            type: iface.type,
            state: iface.state,
            mtu: typeof iface.mtu === 'number' ? iface.mtu : undefined,
            ...(lldp.length > 0 ? { lldp } : {})
        };
    });
};

const localnetRow = (record: NetworkRecord, nns: NodeNetworkState, node: string): Omit<PlacementRow, 'logicalPath'> => {
    const physnet = record.physicalNetworkName || '';
    const interfaces = nns.status?.currentState?.interfaces ?? [];
    const mapping = getActiveBridgeMappings(nns).find((m) => m.localnet === physnet);
    if (!mapping) {
        return {
            node,
            status: 'not-wired',
            reason: `No bridge mapping names ${physnet}.`,
            uplinks: [],
            physicalPath: physicalViewPath(node, record.graphNodeId)
        };
    }
    const present = interfaces.some((iface) => iface.name === mapping.bridge && BRIDGE_TYPES.includes(iface.type));
    return {
        node,
        status: present ? 'wired' : 'not-wired',
        reason: present
            ? `${physnet} is mapped to ${mapping.bridge}.`
            : `${physnet} is mapped to ${mapping.bridge}, which this node does not report.`,
        bridge: { name: mapping.bridge, present },
        uplinks: present ? describeUplinks(mapping.bridge, interfaces) : [],
        physicalPath: physicalViewPath(node, bridgeMappingNodeId(physnet))
    };
};

const sameNetwork = (match: PrimaryNetworkMatch, record: NetworkRecord): boolean =>
    match.kind === record.kind && match.name === record.name
    && (record.kind === 'cudn' || match.namespace === record.namespace);

/** The basis of a VRF match in words; mirrors the VRF drawer's Serves Primary Network fact. */
const vrfMatchHint = (match: PrimaryNetworkMatch): string => {
    const corroborated = match.corroboration
        ? ` Port ${match.corroboration.port} address ${match.corroboration.address} lies inside subnet ${match.corroboration.subnet}.`
        : '';
    if (match.signals.includes('status')) return `The network's status.vrfName names this VRF.${corroborated}`;
    if (match.signals.includes('network-id')) {
        return `Matched by network ID: the VRF is named mp${match.networkId}-udn-vrf and NetworkAttachmentDefinition `
            + `${match.nad?.namespace}/${match.nad?.name} carries ${NETWORK_ID_ANNOTATION}: ${match.networkId}.${corroborated}`;
    }
    // The subnet signal only corroborates; its sentence follows.
    return `Matched by ${match.signals.filter((signal) => signal !== 'subnet').join(' and ')}: the VRF carries the network's name, `
        + `or its first 15 characters.${corroborated}`;
};

const primaryRow = (
    record: NetworkRecord,
    nns: NodeNetworkState,
    node: string,
    inputs: NetworkInputs
): Omit<PlacementRow, 'logicalPath'> => {
    const interfaces = nns.status?.currentState?.interfaces ?? [];
    // A primary NAD is matched through the network it belongs to.
    const target: NetworkRecord = record.kind === 'nad' && record.owner
        ? { ...record, kind: record.owner.kind, name: record.owner.name, namespace: record.owner.namespace }
        : record;
    for (const vrf of interfaces.filter((iface) => iface.type === 'vrf')) {
        const match = findPrimaryNetworkForVrf(vrf, inputs.cudns, inputs.udns, interfaces, inputs.nads);
        if (match && sameNetwork(match, target)) {
            const managementPorts = getVrfConnectionInfo(vrf, interfaces).brIntPorts
                .filter((port) => port.name.startsWith(MANAGEMENT_PORT_PREFIX))
                .map((port) => ({ name: port.name, state: port.state }));
            return {
                node,
                status: 'wired',
                reason: `VRF ${vrf.name} serves ${record.name}.`,
                uplinks: [],
                vrf: {
                    name: vrf.name,
                    state: vrf.state,
                    provenance: match.signals.includes('status') ? 'declared' : 'inferred',
                    hint: vrfMatchHint(match),
                    managementPorts
                },
                physicalPath: physicalViewPath(node, vrfNodeId(vrf.name))
            };
        }
    }
    return {
        node,
        status: 'not-wired',
        reason: `No VRF on this node was matched to ${record.name}.`,
        uplinks: [],
        physicalPath: physicalViewPath(node, record.graphNodeId)
    };
};

const bridgeRow = (record: NetworkRecord, nns: NodeNetworkState, node: string): Omit<PlacementRow, 'logicalPath'> => {
    const bridge = record.bridge || '';
    const interfaces = nns.status?.currentState?.interfaces ?? [];
    const present = interfaces.some((iface) => iface.name === bridge);
    return {
        node,
        status: present ? 'wired' : 'not-wired',
        reason: present ? `The node reports ${bridge}.` : `The node does not report ${bridge}.`,
        bridge: { name: bridge, present },
        uplinks: present ? describeUplinks(bridge, interfaces) : [],
        physicalPath: physicalViewPath(node, present ? ifaceNodeId(bridge) : record.graphNodeId)
    };
};

/**
 * The names a pod's attachment to this network goes by: `namespace/nad` for each NAD of
 * the network. A CUDN has one per selected namespace, read from its generated NADs and
 * from its NetworkCreated condition, which still names them when NADs cannot be listed.
 * Empty for a CUDN with neither, and for the cluster default network, whose attachments
 * are not counted. Names, never subnets: networks may overlap.
 */
export const networkAttachmentNames = (record: NetworkRecord, inputs: NetworkInputs): string[] => {
    if (record.clusterDefault) return [];
    const declared = record.kind === 'cudn'
        ? getCudnAssociatedNamespaces(record.resource as ClusterUserDefinedNetwork).map((ns) => `${ns}/${record.name}`)
        : [`${record.namespace}/${record.name}`];
    const generated = generatedNads(record, inputs).map((nad) => `${namespaceOf(nad)}/${nad.metadata?.name}`);
    return Array.from(new Set([...declared, ...generated])).sort();
};

/** Whether OVN holds this network's attachments: anything but a NAD of another CNI. */
export const isOvnNetwork = (record: NetworkRecord): boolean =>
    record.kind !== 'nad' || record.cniType === OVN_CNI_TYPE;

/** Per-node counts from pods that were read, each workload once across the network's NADs. */
export const workloadCountsFromIndex = (
    index: NetworkAttachmentIndex,
    networks: readonly string[],
): Map<string, NodeWorkloadCount> => {
    const seen = new Map<string, { pod: Set<string>; vm: Set<string> }>();
    networks.forEach((network) => {
        index.get(network)?.forEach((attachments, node) => {
            const onNode = seen.get(node) ?? { pod: new Set<string>(), vm: new Set<string>() };
            seen.set(node, onNode);
            attachments.forEach(({ workload }) => {
                onNode[workload.kind].add(`${workload.namespace}/${workload.name}`);
            });
        });
    });
    return new Map(Array.from(seen, ([node, { pod, vm }]) => [node, { pods: pod.size, vms: vm.size }]));
};

/**
 * Per-node counts from the collector, and the nodes it could speak for. A launcher pod is
 * a VM where KubeVirt is served, and an ordinary pod anywhere else.
 */
export const workloadCountsFromCollector = (
    response: NetworkAttachmentsResponse,
    networks: readonly string[],
    kubevirt: boolean,
): { counts: Map<string, NodeWorkloadCount>; coveredNodes: Set<string> } => {
    const wanted = new Set(networks);
    const counts = new Map<string, NodeWorkloadCount>();
    response.networks.filter(({ nad }) => wanted.has(nad)).forEach(({ nodes }) => {
        nodes.forEach(({ nodeName, pods, virtLaunchers }) => {
            const count = counts.get(nodeName) ?? { pods: 0, vms: 0 };
            counts.set(nodeName, {
                pods: count.pods + pods + (kubevirt ? 0 : virtLaunchers),
                vms: count.vms + (kubevirt ? virtLaunchers : 0),
            });
        });
    });
    return { counts, coveredNodes: new Set(response.zones) };
};

const workloadsOnNode = (node: string, workloads: NetworkWorkloads): PlacementWorkloads => {
    if (workloads.state !== 'known') return { state: workloads.state };
    if (workloads.coveredNodes && !workloads.coveredNodes.has(node)) return { state: 'unknown' };
    const count = workloads.counts.get(node);
    const pods = count?.pods ?? 0;
    if (!workloads.kubevirt) return { state: 'known', pods };
    return { state: 'known', pods, vms: workloads.vmsUnknown ? 'unknown' : count?.vms ?? 0 };
};

const countText = (count: number, noun: string): string => `${count} ${noun}${count === 1 ? '' : 's'}`;

/** A row's Attached cell: "2 pods, 1 VM", "2 pods" without KubeVirt, "unknown", or "-" until asked. */
export const placementWorkloadsText = (workloads: PlacementWorkloads): string | undefined => {
    if (workloads.state === 'loading') return undefined;
    if (workloads.state === 'unknown') return 'unknown';
    if (workloads.state === 'on-request') return '-';
    const pods = countText(workloads.pods, 'pod');
    if (workloads.vms === undefined) return pods;
    return `${pods}, ${workloads.vms === 'unknown' ? 'VMs unknown' : countText(workloads.vms, 'VM')}`;
};

/** The line under the placement table about where its Attached counts came from. */
export const placementWorkloadsNote = (workloads: NetworkWorkloads, nodes: readonly string[]): string | undefined => {
    if (workloads.state === 'unknown') return workloads.reason;
    if (workloads.state !== 'known') return undefined;
    const parts: string[] = [];
    if (workloads.source === 'collector') {
        parts.push('Counted from OVN snapshots, which can lag by a few minutes.');
        const { coveredNodes } = workloads;
        const missing = coveredNodes ? nodes.filter((node) => !coveredNodes.has(node)).length : 0;
        if (missing > 0) parts.push(`${countText(missing, 'node')} without live OVN data.`);
    }
    if (workloads.countedAt) parts.push(`Counted once at ${new Date(workloads.countedAt).toLocaleTimeString()}.`);
    if (workloads.vmsUnknown) parts.push(workloads.vmsUnknown);
    return parts.length > 0 ? parts.join(' ') : undefined;
};

/**
 * One row per node with a NodeNetworkState: is the network wired there, and on what.
 * Rows are sorted by node name; `wired` counts the wired rows. Given `workloads`, each
 * row also says what is attached to the network on that node.
 */
export interface PlacementOptions {
    /** The collector gate is on: a wired primary network's rows link to its gateway routers. */
    collectorEnabled?: boolean;
    /** Zone databases this tab already holds, by node, read for the gateway router's actual name. */
    zones?: NetworkMasqueradeContext['zones'];
}

/** A wired primary row's gateway router: the name a remembered zone shows, else the one OVN-Kubernetes gives it. */
const placementGatewayRouter = (
    record: NetworkRecord,
    node: string,
    options: PlacementOptions,
): PlacementRow['gatewayRouter'] => {
    if (!options.collectorEnabled || !isPrimaryNetwork(record)) return undefined;
    const ovnNetwork = ovnNetworkNameOfRecord(record);
    if (!ovnNetwork) return undefined;
    const zone = options.zones?.find((candidate) => candidate.node === node);
    const name = (zone && gatewayRouterIn(zone.database, ovnNetwork, node)?.name) || gatewayRouterName(ovnNetwork, node);
    return { name, path: constructDetailPath(node, 'router', name, { tab: 'routes' }) };
};

export const buildPlacement = (
    record: NetworkRecord,
    nodeNetworkStates: NodeNetworkState[],
    inputs: NetworkInputs,
    workloads?: NetworkWorkloads,
    options: PlacementOptions = {}
): Placement => {
    const rows = nodeNetworkStates
        .map((nns): PlacementRow => {
            const node = nns.metadata?.name || '';
            const row = record.placement === 'localnet' ? localnetRow(record, nns, node)
                : record.placement === 'primary' ? primaryRow(record, nns, node, inputs)
                    : record.placement === 'bridge' ? bridgeRow(record, nns, node)
                        : {
                            node,
                            status: 'not-checked' as const,
                            reason: 'Nothing node-local is checked for this network.',
                            uplinks: [],
                            physicalPath: physicalViewPath(node, record.graphNodeId)
                        };
            const gatewayRouter = row.status === 'wired' ? placementGatewayRouter(record, node, options) : undefined;
            return {
                ...row,
                logicalPath: logicalViewPath(node),
                ...(gatewayRouter ? { gatewayRouter } : {}),
                ...(workloads ? { workloads: workloadsOnNode(node, workloads) } : {})
            };
        })
        .sort((a, b) => a.node.localeCompare(b.node));
    return {
        mode: record.placement,
        rows,
        wired: rows.filter((row) => row.status === 'wired').length,
        total: rows.length
    };
};

/** "Wired on 4 of 10 nodes", or undefined when the matrix checks nothing for the network. */
export const placementSummary = (placement: Placement): string | undefined => {
    if (placement.mode === 'none') return undefined;
    return `Wired on ${placement.wired} of ${placement.total} node${placement.total === 1 ? '' : 's'}`;
};
