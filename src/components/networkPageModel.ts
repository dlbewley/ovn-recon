/*
 * The network pages (ovn-recon-nfs.1, nfs.2): one page per ClusterUserDefinedNetwork,
 * UserDefinedNetwork and NAD-only network, answering "what is it, and on which nodes is
 * it wired?". Pure: no React, no hooks. Relationships come from the selectors the
 * physical graph and the findings engine already use; nothing here re-derives them.
 *
 * The placement matrix states facts. It raises no warnings: a Localnet network mapped on
 * only some nodes is often deliberate (ovn-recon-nfs.2 notes), and the one case that is a
 * warning, a network mapped on no node, is the findings engine's localnet-unmapped rule.
 */

export type NetworkKind = 'cudn' | 'udn' | 'nad';

export const NETWORKS_PATH = '/ovn-recon/networks';

/** Where one network lives: what a network page URL carries. */
export interface NetworkAddress {
    kind: NetworkKind;
    name: string;
    /** Set for UDNs and NADs; a CUDN is cluster-scoped. */
    namespace?: string;
}

/** The watched lists a network page reads. */
export interface NetworkInputs {
    cudns: ClusterUserDefinedNetwork[];
    udns: UserDefinedNetwork[];
    nads: NetworkAttachmentDefinition[];
    routeAdvertisements: RouteAdvertisements[];
}

/**
 * Which per-node check the placement matrix runs for a network.
 *
 *   localnet  a bridge mapping names the network's physical network, and the bridge exists
 *   primary   one of the node's VRFs serves the network (findPrimaryNetworkForVrf)
 *   bridge    the node reports the bridge a bridge-CNI NAD names
 *   none      nothing node-local in NodeNetworkState is checked for this network
 */
export type PlacementMode = 'localnet' | 'primary' | 'bridge' | 'none';

export interface NetworkRecord extends NetworkAddress {
    resource: ClusterUserDefinedNetwork | UserDefinedNetwork | NetworkAttachmentDefinition;
    /** The findings engine's address for the object (findingsForNetwork). */
    ref: K8sRef;
    /** The console's address for the object. */
    resourceRef: ResourceRef;
    /** The node the network is drawn as on a node's physical graph. */
    graphNodeId: string;
    /** Localnet, Layer2 or Layer3; for a NAD outside OVN-Kubernetes, its CNI type. */
    topology: string;
    role?: string;
    /** The CNI plugin type, for NADs. */
    cniType?: string;
    physicalNetworkName?: string;
    /** Why the physical network name is inferred, when it is a default rather than a field. */
    physicalNetworkInferred?: string;
    /** The bridge a bridge-CNI NAD attaches to. */
    bridge?: string;
    /** Set when the bridge name was pattern-matched out of a config that did not parse. */
    bridgeInferred?: string;
    placement: PlacementMode;
    /**
     * Set on the NAD OVN-Kubernetes creates for the cluster's default pod network. Its
     * config declares no topology, so the record says what the NAD is instead.
     */
    clusterDefault?: boolean;
    /** For a NAD generated by a CUDN or UDN: that network. */
    owner?: NetworkAddress & { inferred?: string };
}

const OVN_CNI_TYPE = 'ovn-k8s-cni-overlay';
const OVN_API = 'k8s.ovn.org/v1';
const NAD_API = 'k8s.cni.cncf.io/v1';
const MANAGEMENT_PORT_PREFIX = 'ovn-k8s-mp';

/** What stands in for a topology on the cluster default network's NAD. */
export const CLUSTER_DEFAULT_LABEL = 'Cluster default network';
/** The namespaces OVN-Kubernetes runs in: OpenShift's, and upstream's. */
const OVN_NAMESPACES = ['openshift-ovn-kubernetes', 'ovn-kubernetes'];
const CLUSTER_DEFAULT_NAD = 'default';

/**
 * Whether a NAD is the one OVN-Kubernetes creates for the cluster's default pod
 * network: named `default`, in OVN-Kubernetes' own namespace, of its CNI type.
 */
export const isClusterDefaultNad = (nad: NetworkAttachmentDefinition): boolean =>
    nad.metadata?.name === CLUSTER_DEFAULT_NAD
    && OVN_NAMESPACES.includes(nad.metadata?.namespace || '')
    && asString(parseNadConfig(nad.spec?.config)?.type) === OVN_CNI_TYPE;

const capitalizeTopology = (value: string): string => {
    const lower = value.toLowerCase();
    if (lower === 'localnet') return 'Localnet';
    if (lower === 'layer2') return 'Layer2';
    if (lower === 'layer3') return 'Layer3';
    return value;
};

const capitalize = (value: string): string => value.charAt(0).toUpperCase() + value.slice(1);

const asRecord = (value: unknown): Record<string, unknown> | undefined =>
    value && typeof value === 'object' && !Array.isArray(value) ? value as Record<string, unknown> : undefined;

const asString = (value: unknown): string | undefined =>
    typeof value === 'string' && value !== '' ? value : undefined;

const asPositive = (value: unknown): number | undefined => {
    const n = typeof value === 'string' && value.trim() !== '' ? Number(value) : value;
    return typeof n === 'number' && Number.isFinite(n) && n > 0 ? n : undefined;
};

// --- Paths -------------------------------------------------------------------

/** The network page for an address. */
export const networkPath = (address: NetworkAddress): string => {
    const name = encodeURIComponent(address.name);
    if (address.kind === 'cudn') return `${NETWORKS_PATH}/cudn/${name}`;
    return `${NETWORKS_PATH}/${address.kind}/${encodeURIComponent(address.namespace || 'default')}/${name}`;
};

const decode = (value: string): string => {
    try {
        return decodeURIComponent(value);
    } catch {
        return value;
    }
};

/**
 * What a network page URL asks for: the list, one network, or nothing this module
 * serves (a malformed path, which renders the empty state).
 */
export const parseNetworkPath = (pathname: string): { list: true } | NetworkAddress | null => {
    const index = pathname.indexOf(NETWORKS_PATH);
    if (index < 0) return null;
    const rest = pathname.slice(index + NETWORKS_PATH.length).split('/').filter(Boolean).map(decode);
    if (rest.length === 0) return { list: true };
    const [kind, ...parts] = rest;
    if (kind === 'cudn' && parts.length === 1) return { kind, name: parts[0] };
    if ((kind === 'udn' || kind === 'nad') && parts.length === 2) {
        return { kind, namespace: parts[0], name: parts[1] };
    }
    return null;
};

/** The node's physical view with one graph node selected. */
export const physicalViewPath = (node: string, selectId?: string): string =>
    `/ovn-recon/node-network-state/${encodeURIComponent(node)}${selectId ? withSelectParam('', selectId) : ''}`;

export const logicalViewPath = (node: string): string => `/ovn-recon/ovn/${encodeURIComponent(node)}`;

// --- Owners and records ------------------------------------------------------

const ownedBy = (resource: { metadata?: { ownerReferences?: { kind: string; name: string }[] } }, kind: string) =>
    (resource.metadata?.ownerReferences ?? []).find((owner) => owner.kind === kind);

/**
 * The CUDN or UDN that generated a NAD, when one did. An owner reference is the
 * declared signal. Without one, a NAD whose config names a CUDN's `cluster_udn_<name>`
 * network, or that shares its namespace and name with a UDN, is matched by convention
 * and the result says so.
 */
export const findNadOwner = (
    nad: NetworkAttachmentDefinition,
    inputs: Pick<NetworkInputs, 'cudns' | 'udns'>
): NetworkRecord['owner'] => {
    const namespace = nad.metadata?.namespace || 'default';
    const cudnOwner = ownedBy(nad, 'ClusterUserDefinedNetwork');
    if (cudnOwner) return { kind: 'cudn', name: cudnOwner.name };
    const udnOwner = ownedBy(nad, 'UserDefinedNetwork');
    if (udnOwner) return { kind: 'udn', name: udnOwner.name, namespace };

    const configName = asString(parseNadConfig(nad.spec?.config)?.name);
    const cudn = configName?.startsWith(CUDN_NETWORK_PREFIX)
        ? inputs.cudns.find((c) => `${CUDN_NETWORK_PREFIX}${c.metadata?.name}` === configName)
        : undefined;
    if (cudn) {
        return {
            kind: 'cudn',
            name: cudn.metadata?.name || '',
            inferred: `The NAD has no owner reference; its config names network ${configName}, `
                + `the name a ClusterUserDefinedNetwork's NADs carry.`
        };
    }
    const udn = inputs.udns.find((u) =>
        u.metadata?.name === nad.metadata?.name && (u.metadata?.namespace || 'default') === namespace);
    if (udn) {
        return {
            kind: 'udn',
            name: udn.metadata?.name || '',
            namespace,
            inferred: 'The NAD has no owner reference; a UserDefinedNetwork with its namespace and name exists.'
        };
    }
    return undefined;
};

const describeCudn = (cudn: ClusterUserDefinedNetwork, inputs: NetworkInputs): NetworkRecord => {
    const name = cudn.metadata?.name || '';
    const network = cudn.spec?.network;
    const topology = network?.topology || 'Unknown';
    const layer = topology === 'Layer2' ? network?.layer2 : topology === 'Layer3' ? network?.layer3 : undefined;
    const localnet = topology === 'Localnet'
        ? getLocalnetNetworks([cudn], inputs.nads)[0]
        : undefined;
    const role = topology === 'Localnet'
        ? (network?.localnet?.role || network?.localNet?.role || 'Secondary')
        : layer?.role;
    return {
        kind: 'cudn',
        name,
        resource: cudn,
        ref: cudnRef(cudn),
        resourceRef: { apiVersion: OVN_API, kind: 'ClusterUserDefinedNetwork', name },
        graphNodeId: cudnNodeId(name),
        topology,
        role,
        physicalNetworkName: localnet?.physicalNetworkName,
        placement: topology === 'Localnet' ? 'localnet' : role === 'Primary' ? 'primary' : 'none'
    };
};

const describeUdn = (udn: UserDefinedNetwork): NetworkRecord => {
    const name = udn.metadata?.name || '';
    const namespace = udn.metadata?.namespace || 'default';
    const { topology, role } = getUdnTopologyAndRole(udn);
    return {
        kind: 'udn',
        name,
        namespace,
        resource: udn,
        ref: udnRef(udn),
        resourceRef: { apiVersion: OVN_API, kind: 'UserDefinedNetwork', name, namespace },
        graphNodeId: udnNodeId(udn),
        topology,
        role: role === 'Unknown' ? undefined : role,
        placement: role === 'Primary' ? 'primary' : 'none'
    };
};

const describeNad = (nad: NetworkAttachmentDefinition, inputs: NetworkInputs): NetworkRecord => {
    const name = nad.metadata?.name || '';
    const namespace = nad.metadata?.namespace || 'default';
    const config = parseNadConfig(nad.spec?.config);
    const cniType = asString(config?.type);
    const base = {
        kind: 'nad' as const,
        name,
        namespace,
        resource: nad,
        ref: nadRef(nad),
        resourceRef: { apiVersion: NAD_API, kind: 'NetworkAttachmentDefinition', name, namespace },
        graphNodeId: nadNodeId(nad),
        cniType,
        owner: findNadOwner(nad, inputs)
    };

    if (cniType === OVN_CNI_TYPE) {
        const declaredTopology = asString(config?.topology);
        if (!declaredTopology && isClusterDefaultNad(nad)) {
            return { ...base, topology: CLUSTER_DEFAULT_LABEL, clusterDefault: true, placement: 'none' };
        }
        const topology = capitalizeTopology(declaredTopology || 'Unknown');
        const role = asString(config?.role);
        // getLocalnetNetworks reads a standalone NAD; a generated NAD's own config states
        // the same physical network, so read it as if it stood alone.
        const localnet = topology === 'Localnet'
            ? getLocalnetNetworks([], [{ ...nad, metadata: { ...nad.metadata, ownerReferences: [] } }])[0]
            : undefined;
        return {
            ...base,
            topology,
            role: role ? capitalize(role) : (topology === 'Localnet' ? 'Secondary' : undefined),
            physicalNetworkName: localnet?.physicalNetworkName,
            physicalNetworkInferred: localnet?.physicalNetworkInferred,
            placement: topology === 'Localnet' ? 'localnet' : role === 'primary' ? 'primary' : 'none'
        };
    }

    // A bridge-CNI NAD names its bridge; getNadUpstreamNodeIds pattern-matches it out of a
    // config that did not parse, which makes the bridge name inferred.
    const bridge = getNadUpstreamNodeIds(nad).find((id) => !id.startsWith('ovn:'));
    return {
        ...base,
        topology: cniType ?? 'Unknown',
        bridge,
        bridgeInferred: bridge && !config
            ? 'Pattern-matched out of a CNI config that did not parse as JSON.'
            : undefined,
        placement: bridge ? 'bridge' : 'none'
    };
};

const namespaceOf = (resource: { metadata?: { namespace?: string } }): string => resource.metadata?.namespace || 'default';

/** The network an address names, or undefined when no such object is watched. */
export const findNetwork = (address: NetworkAddress, inputs: NetworkInputs): NetworkRecord | undefined => {
    if (address.kind === 'cudn') {
        const cudn = inputs.cudns.find((c) => c.metadata?.name === address.name);
        return cudn ? describeCudn(cudn, inputs) : undefined;
    }
    if (address.kind === 'udn') {
        const udn = inputs.udns.find((u) => u.metadata?.name === address.name && namespaceOf(u) === address.namespace);
        return udn ? describeUdn(udn) : undefined;
    }
    const nad = inputs.nads.find((n) => n.metadata?.name === address.name && namespaceOf(n) === address.namespace);
    return nad ? describeNad(nad, inputs) : undefined;
};

const KIND_ORDER: Record<NetworkKind, number> = { cudn: 0, udn: 1, nad: 2 };

/**
 * Every network for the list: each CUDN, each UDN, and each NAD that no CUDN or UDN
 * generated. A generated NAD is one copy of its network, listed under that network.
 */
export const listNetworks = (inputs: NetworkInputs): NetworkRecord[] => [
    ...inputs.cudns.map((cudn) => describeCudn(cudn, inputs)),
    ...inputs.udns.map(describeUdn),
    ...inputs.nads.map((nad) => describeNad(nad, inputs)).filter((record) => !record.owner)
].sort((a, b) => KIND_ORDER[a.kind] - KIND_ORDER[b.kind]
    || (a.namespace ?? '').localeCompare(b.namespace ?? '')
    || a.name.localeCompare(b.name));

