/** The OVN-Kubernetes CNI type a Localnet NAD declares. */
const OVN_CNI_TYPE = 'ovn-k8s-cni-overlay';

/** Interface types that carry a bridge's traffic off the host. */
const UPLINK_TYPES = ['ethernet', 'bond', 'vlan', 'team'];

/** A network that lands on a physical network through a bridge mapping. */
export interface LocalnetNetwork {
    ref: K8sRef;
    /** The graph node the network is drawn as on a node's physical graph. */
    graphNodeId: string;
    physicalNetworkName: string;
    /** Where the physical network name was read, in dotted form. */
    physicalNetworkPath: string;
    /** Set when the name is a default rather than a stated field. */
    physicalNetworkInferred?: string;
    /** The MTU the network declares, with where it was read. Absent when none is. */
    mtu?: { value: number; source: K8sRef; path: string };
}

type LocalnetSpec = { physicalNetworkName?: string; mtu?: number };

const cudnLocalnetSpec = (cudn: ClusterUserDefinedNetwork): { spec: LocalnetSpec; key: string } | undefined => {
    const network = cudn.spec?.network;
    if ((network?.topology || '').toLowerCase() !== 'localnet') return undefined;
    if (network?.localnet) return { spec: network.localnet as LocalnetSpec, key: 'localnet' };
    if (network?.localNet) return { spec: network.localNet as LocalnetSpec, key: 'localNet' };
    return undefined;
};

const positiveInt = (value: unknown): number | undefined => {
    const n = typeof value === 'string' && value.trim() !== '' ? Number(value) : value;
    return typeof n === 'number' && Number.isInteger(n) && n > 0 ? n : undefined;
};

/**
 * True when a NAD was generated by a ClusterUserDefinedNetwork. Such a NAD is one
 * copy per namespace of the CUDN's network, so findings belong to the CUDN.
 *
 * The owner reference is the reliable signal; a config name carrying the CUDN's
 * `cluster_udn_<name>` network name is the fallback for a NAD stripped of owner
 * references. Only used to SKIP a NAD, never to fire on one.
 */
export const isCudnGeneratedNad = (
    nad: NetworkAttachmentDefinition,
    cudns: ClusterUserDefinedNetwork[]
): boolean => {
    if ((nad.metadata?.ownerReferences ?? []).some((owner) => owner.kind === 'ClusterUserDefinedNetwork')) {
        return true;
    }
    const name = parseNadConfig(nad.spec?.config)?.name;
    return typeof name === 'string'
        && cudns.some((cudn) => name === `${CUDN_NETWORK_PREFIX}${cudn.metadata?.name}`);
};

/** The Localnet network a NAD defines, when its config is an OVN-Kubernetes Localnet one. */
const nadLocalnetNetwork = (nad: NetworkAttachmentDefinition): LocalnetNetwork | undefined => {
    const config = parseNadConfig(nad.spec?.config);
    if (!config || config.type !== OVN_CNI_TYPE || config.topology !== 'localnet') return undefined;
    const ref = nadRef(nad);
    const stated = typeof config.physicalNetworkName === 'string' && config.physicalNetworkName
        ? config.physicalNetworkName : undefined;
    const fallback = typeof config.name === 'string' && config.name ? config.name : undefined;
    const physicalNetworkName = stated ?? fallback;
    if (!physicalNetworkName) return undefined;
    const mtu = positiveInt(config.mtu);
    return {
        ref,
        graphNodeId: nadNodeId(nad),
        physicalNetworkName,
        physicalNetworkPath: stated ? 'spec.config.physicalNetworkName' : 'spec.config.name',
        physicalNetworkInferred: stated
            ? undefined
            : 'No physicalNetworkName is set; OVN-Kubernetes then uses the network name as the bridge mapping name.',
        mtu: mtu ? { value: mtu, source: ref, path: 'spec.config.mtu' } : undefined
    };
};

/**
 * Every Localnet network in the cluster: each Localnet CUDN, and each Localnet NAD
 * that no CUDN generated. A CUDN with no MTU of its own takes the MTU its generated
 * NADs carry, which is what OVN-Kubernetes applied.
 */
export const getLocalnetNetworks = (
    cudns: ClusterUserDefinedNetwork[],
    nads: NetworkAttachmentDefinition[]
): LocalnetNetwork[] => {
    const fromCudns = cudns.flatMap((cudn): LocalnetNetwork[] => {
        const localnet = cudnLocalnetSpec(cudn);
        const physicalNetworkName = localnet?.spec.physicalNetworkName;
        if (!localnet || !physicalNetworkName) return [];
        const ref = cudnRef(cudn);
        const name = cudn.metadata?.name || '';
        const declared = positiveInt(localnet.spec.mtu);
        let mtu: LocalnetNetwork['mtu'] = declared
            ? { value: declared, source: ref, path: `spec.network.${localnet.key}.mtu` }
            : undefined;
        if (!mtu) {
            const generated = nads.find((nad) =>
                (nad.metadata?.ownerReferences ?? []).some((owner) =>
                    owner.kind === 'ClusterUserDefinedNetwork' && owner.name === name)
                && positiveInt(parseNadConfig(nad.spec?.config)?.mtu));
            const value = generated ? positiveInt(parseNadConfig(generated.spec?.config)?.mtu) : undefined;
            if (generated && value) mtu = { value, source: nadRef(generated), path: 'spec.config.mtu' };
        }
        return [{
            ref,
            graphNodeId: cudnNodeId(name),
            physicalNetworkName,
            physicalNetworkPath: `spec.network.${localnet.key}.physicalNetworkName`,
            mtu
        }];
    });
    const fromNads = nads
        .filter((nad) => !isCudnGeneratedNad(nad, cudns))
        .map(nadLocalnetNetwork)
        .filter((network): network is LocalnetNetwork => Boolean(network));
    return [...fromCudns, ...fromNads];
};

/** A node's bridge mappings, without any nmstate has been asked to remove. */
export const getActiveBridgeMappings = (nns: NodeNetworkState | undefined): OvnBridgeMapping[] =>
    (nns?.status?.currentState?.ovn?.['bridge-mappings'] ?? [])
        .filter((mapping) => mapping && mapping.localnet && mapping.state !== 'absent');

/**
 * The interfaces that carry a bridge's traffic off the host: its ports of a physical
 * or aggregate type. Patch ports, the bridge's own internal port and other OVS
 * internal ports are not uplinks.
 */
export const getBridgeUplinks = (bridge: string, interfaces: Interface[]): Interface[] =>
    interfaces.filter((iface) =>
        (iface.controller || iface.master) === bridge && UPLINK_TYPES.includes(iface.type));

/** The ports a VRF interface declares, whichever shape nmstate used. */
export const getVrfPorts = (vrf: Interface): string[] => {
    const port = vrf.vrf?.port;
    if (Array.isArray(port)) return port.filter((p): p is string => typeof p === 'string' && p !== '');
    return typeof port === 'string' && port ? [port] : [];
};
