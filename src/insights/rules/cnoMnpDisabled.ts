import { isCudnGeneratedNad } from '../network';
import { operatorNetworkRef, plural, prerequisite, unmetEvidence } from '../cno';
import { nameList } from '../masquerade';
import { makeFinding, multiNetworkPolicyRef, nadRef } from '../refs';
import type { Evidence, K8sRef, PhysicalRule } from '../types';

const qualified = (ref: K8sRef): string => `${ref.namespace}/${ref.name}`;

/**
 * cno-mnp-disabled (ovn-recon-n7r.3): the operator configuration leaves
 * MultiNetworkPolicies, or the networks themselves, without effect. Two cases, read
 * from the MultiNetworkPolicy checklist's prerequisites:
 *
 *   multi-network disabled  `spec.disableMultiNetwork: true` while NADs (not
 *                           generated by a CUDN, which is the network) or
 *                           MultiNetworkPolicies exist: Multus is not deployed, so
 *                           nothing attaches to the NADs and no policy applies.
 *   policies not enforced   multi-network is on but `useMultiNetworkPolicy` is not
 *                           true while MultiNetworkPolicies exist: they are ignored.
 *
 * At most one finding, on the network configuration; the first case covers the
 * second. Without the MultiNetworkPolicy list (the kind not served, or not visible)
 * only the NADs are read. This pairs with the logical mnp-missing-nad rule.
 */
export const cnoMnpDisabled: PhysicalRule = {
    id: 'cno-mnp-disabled',
    severity: 'warning',
    scope: 'network',
    domain: 'physical',
    title: 'MultiNetworkPolicies or networks left without effect by the network operator',
    evaluate: ({ cluster }) => {
        const config = cluster.networkConfig;
        const multus = prerequisite(config, 'multi-network-policy', 'multi-network-enabled');
        const enforce = prerequisite(config, 'multi-network-policy', 'use-multi-network-policy');
        if (!multus || !enforce) return [];

        const nads = cluster.nads.filter((nad) => !isCudnGeneratedNad(nad, cluster.cudns)).map(nadRef);
        const policies = (cluster.multiNetworkPolicies ?? []).map((policy) =>
            multiNetworkPolicyRef(policy.metadata?.namespace || 'default', policy.metadata?.name || ''));
        const nadEvidence: Evidence[] = nads.length > 0 ? [{
            fact: `${plural(nads.length, 'NetworkAttachmentDefinition')} ${nads.length === 1 ? 'exists' : 'exist'}.`,
            sources: nads
        }] : [];
        const policyEvidence: Evidence[] = policies.length > 0 ? [{
            fact: `${plural(policies.length, 'MultiNetworkPolicy', 'MultiNetworkPolicies')} ${policies.length === 1 ? 'exists' : 'exist'}.`,
            sources: policies
        }] : [];
        const base = {
            ruleId: cnoMnpDisabled.id,
            severity: cnoMnpDisabled.severity,
            subject: { kind: 'k8s' as const, ref: operatorNetworkRef },
            scope: {}
        };

        if (multus.state === 'unmet') {
            if (nads.length === 0 && policies.length === 0) return [];
            const what = [
                ...(nads.length > 0 ? [`${plural(nads.length, 'NetworkAttachmentDefinition')} (${nameList(nads.map(qualified))})`] : []),
                ...(policies.length > 0
                    ? [`${plural(policies.length, 'MultiNetworkPolicy', 'MultiNetworkPolicies')} (${nameList(policies.map(qualified))})`]
                    : [])
            ];
            return [makeFinding({
                ...base,
                summary: `Multi-network is disabled, so ${what.join(' and ')} have no effect.`,
                evidence: [unmetEvidence(multus), ...nadEvidence, ...policyEvidence],
                remedy: {
                    text: 'Set disableMultiNetwork to false in the network operator configuration so Multus is deployed, '
                        + 'and useMultiNetworkPolicy to true if MultiNetworkPolicies should be enforced; or delete what '
                        + 'is not wanted.',
                    target: operatorNetworkRef,
                    path: multus.sourcePath
                }
            }, 'multi-network')];
        }

        if (enforce.state !== 'unmet' || policies.length === 0) return [];
        return [makeFinding({
            ...base,
            summary: `${plural(policies.length, 'MultiNetworkPolicy', 'MultiNetworkPolicies')} `
                + `(${nameList(policies.map(qualified))}) ${policies.length === 1 ? 'is' : 'are'} ignored: `
                + `useMultiNetworkPolicy is ${enforce.actual}.`,
            evidence: [unmetEvidence(enforce), ...policyEvidence],
            remedy: {
                text: 'Set useMultiNetworkPolicy to true in the network operator configuration to enforce them, or '
                    + 'delete the MultiNetworkPolicies if they are not wanted.',
                target: operatorNetworkRef,
                path: enforce.sourcePath
            }
        }, 'policies')];
    }
};
